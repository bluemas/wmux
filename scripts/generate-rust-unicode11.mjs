/** Derive widths from the same pinned addon used by the renderer, not a newer Unicode database. */
import { Unicode11Addon } from '@xterm/addon-unicode11';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
let provider;
new Unicode11Addon().activate({ unicode: { register: value => { provider = value; } } });
const ranges = [];
for (let start = 0; start <= 0x10ffff;) {
  const width = provider.wcwidth(start);
  let end = start;
  while (end < 0x10ffff && provider.wcwidth(end + 1) === width) end++;
  if (width !== 1) ranges.push([start, end, width]);
  start = end + 1;
}
const source = readFileSync(new URL('../node_modules/@xterm/addon-unicode11/src/UnicodeV11.ts', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const text = `// Generated by scripts/generate-rust-unicode11.mjs. Do not edit.\n// Width data derived from xterm.js Unicode11Addon (MIT; see LICENSE-XTERM).\n// UnicodeV11.ts SHA-256: ${createHash('sha256').update(source).digest('hex')}\n\npub fn width(c: char) -> Option<usize> {\n    let code = c as u32;\n    let index = RANGES.partition_point(|range| range.1 < code);\n    Some(match RANGES.get(index) {\n        Some(&(start, _, width)) if code >= start => width as usize,\n        _ => 1,\n    })\n}\n\nconst RANGES: &[(u32, u32, u8)] = &[\n${ranges.map(([a,b,w]) => `    (0x${a.toString(16)}, 0x${b.toString(16)}, ${w}),`).join('\n')}\n];\n`;
const dest = new URL('../core/wmux-term/vendor/alacritty_terminal/src/wmux_unicode11.rs', import.meta.url);
if (process.argv.includes('--check')) {
  // Git's Windows checkout may use CRLF. Compare generated content, not the
  // checkout's line-ending convention; substantive changes must still fail.
  if (readFileSync(dest, 'utf8').replace(/\r\n/g, '\n') !== text) throw new Error('Rust Unicode table is stale; regenerate it');
} else writeFileSync(dest, text);
