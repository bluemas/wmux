// No #! line: vitest imports this module (officeArtPipeline.test.ts), and a
// module with a shebang cannot be imported under vitest. Run it with `node`.
// Builds the Office page's pixel art (original to this repo) into
// src/renderer/assets/office/: furniture.png, characters.png and
// layout.generated.ts (sprite rectangles and anchors). Deterministic: a rerun
// with unchanged sources writes byte-identical files.
//
//   node scripts/office-art/build-office-art.mjs [out-dir]   (default: src/renderer/assets/office)
//
// See docs/office-art.md for the grid, palette and how to add a look.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Layer, bounds, compose, crop, encodePng, toRgba } from './raster.mjs';
import { RAMPS } from './palette.mjs';
import {
  SEAT,
  SOFA_FRAME,
  SOFA_SEATS,
  STATION,
  TILE_H,
  TILE_W,
  drawChair,
  drawCoffeeTable,
  drawDesk,
  drawFloor,
  drawMonitor,
  drawPlant,
  drawRug,
  drawShelf,
  drawSofa,
  drawWall,
  iso,
  mirrorWall,
} from './furniture.mjs';
import { GENERIC_LOOK, LOOKS, POSES, drawCharacter } from './characters.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT_DIR = join(ROOT, 'src', 'renderer', 'assets', 'office');

const GAP = 2;

/** Every furniture sprite with the pixel that sits on its reference floor point. */
export function buildFurniture() {
  const station = { x: STATION.ox, y: STATION.oy };
  const wall = drawWall(false);
  const window = drawWall(true);
  const wallAnchor = { x: 0, y: wall.h - 9 };
  const list = [
    ['desk', drawDesk(), station],
    ['monitorOff', drawMonitor(false), station],
    ['monitorOn', drawMonitor(true), station],
    ['chair', drawChair(), station],
    ['floor', drawFloor('floor', true), { x: TILE_W / 2, y: 0 }],
    ['carpet', drawFloor('carpet', false), { x: TILE_W / 2, y: 0 }],
    ['wall', wall, wallAnchor],
    ['window', window, wallAnchor],
    ['wallLeft', mirrorWall(wall), { x: wall.w, y: wallAnchor.y }],
    ['windowLeft', mirrorWall(window), { x: window.w, y: wallAnchor.y }],
    ['plant', drawPlant(), { x: 11, y: 26 }],
    ['shelf', drawShelf(), { x: 10, y: 46 }],
    ['sofa', drawSofa(), { x: SOFA_FRAME.ox, y: SOFA_FRAME.oy }],
    ['coffeeTable', drawCoffeeTable(), { x: 14, y: 12 }],
    ['rug', drawRug(), { x: 32, y: 0 }],
  ];
  return list.map(([key, layer, anchor]) => ({ key, layer, anchor }));
}

/** Shelf-pack sprites left to right into rows no wider than maxW. */
function pack(items, maxW) {
  let x = 0;
  let y = 0;
  let rowH = 0;
  for (const it of items) {
    if (x > 0 && x + it.layer.w > maxW) {
      x = 0;
      y += rowH + GAP;
      rowH = 0;
    }
    it.x = x;
    it.y = y;
    x += it.layer.w + GAP;
    rowH = Math.max(rowH, it.layer.h);
  }
  return { w: maxW, h: y + rowH };
}

export function buildSheets() {
  const furniture = buildFurniture();
  const size = pack(furniture, 4 * (STATION.w + GAP) - GAP);
  const fSheet = new Layer(size.w, size.h);
  for (const f of furniture) compose(fSheet, f.layer, f.x, f.y);

  const looks = [...LOOKS, GENERIC_LOOK];
  const cSheet = new Layer(POSES.length * STATION.w, looks.length * STATION.h);
  const frames = {};
  looks.forEach((look, row) => {
    frames[look.id] = {};
    POSES.forEach((pose, col) => {
      const layer = drawCharacter(look, pose);
      compose(cSheet, layer, col * STATION.w, row * STATION.h);
      frames[look.id][pose] = { x: col * STATION.w, y: row * STATION.h, w: STATION.w, h: STATION.h };
    });
  });
  // A fully transparent sprite or frame is a broken template: fail the build.
  for (const f of furniture) {
    if (bounds(f.layer).w <= 0) throw new Error(`furniture sprite ${f.key} is empty`);
  }
  for (const look of looks) for (const pose of POSES) {
    const r = frames[look.id][pose];
    if (bounds(crop(cSheet, r.x, r.y, r.w, r.h)).w <= 0) throw new Error(`character frame ${look.id}.${pose} is empty`);
  }
  return { furniture, fSheet, cSheet, looks, frames };
}

const P = iso(STATION.ox, STATION.oy);

function layoutTs({ furniture, looks, frames }) {
  const charAnchor = P(SEAT.a, SEAT.b, 0);
  const lines = [
    '// Generated by scripts/office-art/build-office-art.mjs. Do not edit by hand;',
    '// change the generator and rerun it.',
    '',
    '/** Sprite rectangles in furniture.png, and the pixel of each sprite that sits on its floor anchor. */',
    'export const FURNITURE_LAYOUT = {',
    ...furniture.map(
      (f) =>
        `  ${f.key}: { x: ${f.x}, y: ${f.y}, w: ${f.layer.w}, h: ${f.layer.h}, anchorX: ${f.anchor.x}, anchorY: ${f.anchor.y} },`,
    ),
    '} as const;',
    '',
    '/** Character frames in characters.png: one row per look, one column per pose. */',
    'export const CHARACTER_LAYOUT = {',
    ...looks.map((l) => {
      const poses = POSES.map((p) => {
        const r = frames[l.id][p];
        return `${p}: { x: ${r.x}, y: ${r.y}, w: ${r.w}, h: ${r.h} }`;
      });
      return `  ${l.id}: { ${poses.join(', ')} },`;
    }),
    '} as const;',
    '',
    `export const GENERIC_LOOK_ID = '${GENERIC_LOOK.id}';`,
    '',
    '/** Station frame (desk, monitors, chair and every character frame share its size and origin). */',
    `export const STATION_LAYOUT = { w: ${STATION.w}, h: ${STATION.h}, deskX: ${STATION.ox}, deskY: ${STATION.oy}, seatX: ${charAnchor[0]}, seatY: ${charAnchor[1]} } as const;`,
    '',
    '/** Where a resting character\'s anchor goes, in sofa-sprite pixels. */',
    `export const SOFA_SEAT_LAYOUT = [${SOFA_SEATS.map(([x, y]) => `{ x: ${x}, y: ${y} }`).join(', ')}] as const;`,
    '',
    `export const TILE_LAYOUT = { w: ${TILE_W}, h: ${TILE_H} } as const;`,
    '',
  ];
  return lines.join('\r\n');
}

/** Render every output in memory: { built, files: { name: Buffer | string } }. Writes nothing. */
export function renderAll() {
  const built = buildSheets();
  const png = (layer) => encodePng(layer.w, layer.h, toRgba(layer, RAMPS));
  return {
    built,
    files: {
      'furniture.png': png(built.fSheet),
      'characters.png': png(built.cSheet),
      'layout.generated.ts': layoutTs(built),
    },
  };
}

/** Write the outputs to outDir (default: src/renderer/assets/office). */
export function writeAll(outDir = OUT_DIR) {
  const { built, files } = renderAll();
  mkdirSync(outDir, { recursive: true });
  for (const [name, data] of Object.entries(files)) writeFileSync(join(outDir, name), data);
  return built;
}

// CLI: `node build-office-art.mjs [out-dir]`.
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const built = writeAll(process.argv[2] ? resolve(process.argv[2]) : OUT_DIR);
  console.log(
    `furniture.png ${built.fSheet.w}x${built.fSheet.h}, characters.png ${built.cSheet.w}x${built.cSheet.h} (${built.looks.length} looks x ${POSES.length} poses)`,
  );
}
